func salonTmux(theme Theme) string {
	return fmt.Sprintf(`# Generated by theme use %s.
set -g @theme-popup-border "%s"
set -g @theme-popup-lines single
set -g popup-border-lines single
set -g popup-border-style "fg=#{@theme-popup-border}"
set -g @theme-popup-bg "default"
set -g @theme-popup-fg "default"
set -g popup-style default

# One quiet line under a rule: the session in gilt, then its windows.
set -g status 2
set -gu status-format
set -g status-format[1] '#{T:status-format[0]}'
set -g status-format[0] '#[fg=%s,bg=default]#{R:─,#{client_width}}'
set -g status-position bottom
set -g status-justify left
set -g status-interval 5
set -g status-left-length 40
set -g status-right-length 40
set -g status-style "bg=default,fg=%s"
set -g set-titles-string '#{?@ws-title,#{@ws-title},#S}:#I:#W'
set -g status-left '#[fg=%s,bg=default,bold] #{?@ws-title,#{@ws-title},#S}  '
set -g status-right '#{?client_prefix,#[fg=%s#,bg=%s#,bold] PREFIX #[default] ,}#[fg=%s]%%H:%%M '

set -g window-status-separator "  "
set -g window-status-format "#[fg=%s,bg=default]#I #W"
set -g window-status-current-format "#[fg=%s,bg=default,bold]#I #W"
set -g window-status-last-style "fg=%s,bg=default"
set -g window-status-activity-style "fg=%s,bg=default"
set -g window-status-bell-style "fg=%s,bg=default,bold"

set -g pane-border-lines single
set -g pane-border-style "fg=%s"
set -g pane-active-border-style "fg=%s"
set -g message-style "fg=%s,bg=%s,bold"
set -g message-command-style "fg=%s,bg=%s"
setw -g mode-style "fg=%s,bg=%s,bold"
set -g clock-mode-colour "%s"
`, theme.ID, c(theme, "accent"),
		c(theme, "surface_alt"),
		c(theme, "fg"),
		c(theme, "accent"),
		c(theme, "bg"), c(theme, "accent"), c(theme, "dim"),
		c(theme, "dim"),
		c(theme, "fg"),
		c(theme, "cyan"), c(theme, "yellow"), c(theme, "red"),
		c(theme, "surface_alt"), c(theme, "accent"),
		c(theme, "bg"), c(theme, "accent"),
		c(theme, "fg"), c(theme, "surface"),
		c(theme, "bg"), c(theme, "accent"),
		c(theme, "accent"))
}
