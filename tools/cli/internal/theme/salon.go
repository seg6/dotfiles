package theme

import (
	"fmt"
)

// Salon is a gallery wall. Windows are works hung on it: no title bars, a gilt
// frame, a deep shadow. The one in focus is lit and the rest are dimmed. The
// shell paints the wall and hangs the theme's painting where a wall is empty.

func salonSway(theme Theme) string {
	gilt := role(theme, "gilt", "accent")
	bronze := role(theme, "bronze", "surface_alt")
	return fmt.Sprintf(`output * bg %s solid_color

default_border pixel 3
default_floating_border pixel 3
title_align left
titlebar_border_thickness 1
client.focused          %s %s $bg %s %s
client.focused_inactive %s %s $fg %s %s
client.unfocused        %s %s $fg %s %s
client.urgent           $urgent $urgent $bg $urgent $urgent

corner_radius 0
smart_corner_radius enable
shadows %s
shadows_on_csd %s
shadow_blur_radius 44
shadow_color #000000b8
shadow_inactive_color #00000090
shadow_offset 0 24

blur disable
default_dim_inactive 0.14

layer_effects "salon" shadows disable
layer_effects "salon" blur disable
layer_effects "salon" corner_radius 0
`, role(theme, "wall", "bg_alt"),
		gilt, gilt, gilt, gilt,
		bronze, bronze, bronze, bronze,
		bronze, bronze, bronze, bronze,
		enable(uiBool(theme, "shadow", true)), enable(uiBool(theme, "shadow", true)))
}

